def get_icon(name: str, size: int = 15, margin_right: int = 6) -> str:
    """Returns an inline monochrome SVG icon element."""
    svg = ICONS.get(name, "")
    if not svg:
        return ""
    # Inject inline styles into the root <svg> tag
    style = (
        f'display:inline-block;vertical-align:-0.15em;width:{size}px;height:{size}px;'
        f'margin-right:{margin_right}px;stroke:currentColor;fill:none;flex-shrink:0;'
    )
    return svg.replace("<svg ", f'<svg style="{style}" ')
