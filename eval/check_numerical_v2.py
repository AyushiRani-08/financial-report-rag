"""
eval/check_numerical_v2.py
Attribution-aware numerical checker — drop-in replacement for the
`check_numerical` function in run_eval.py.

The original checker passes as long as ANY number in the model answer
lands within ±2% of the ground-truth value.  It never verifies the
number belongs to the right field or the right period, so "Cost of
revenue was $391B" passes a revenue question, and "FY2023 revenue was
$383B" passes an FY2024 revenue question.

This module fixes that:
1. Extract candidate numbers AND their surrounding line context.
2. Keep only candidates whose *nearest* field alias belongs to the
   requested line item — so "cost of revenue" cannot satisfy a revenue
   question just because the word "revenue" appears inside it.
3. Reject candidates when the closest period token contradicts the
   expected period (e.g. "FY2023" in an FY2024 answer).
4. The result dict gains two extra keys: `attribution_checked` (bool)
   and `attribution_match` (the matched alias or None).

Alias vocabulary mirrors QUANT_TEMPLATES so the checker and the
question generator are always in sync.
"""

