def _resolve_field(canonical_field: str) -> str:
    """Base alias field for a reported or derived canonical field name."""
    if not canonical_field:
        return ""
    if canonical_field in FIELD_ALIASES:
        return canonical_field
    if canonical_field in DERIVED_FIELD_MAP:
        return DERIVED_FIELD_MAP[canonical_field]
    for suffix in _DERIVED_SUFFIXES:
        if canonical_field.endswith(suffix):
            base = canonical_field[: -len(suffix)]
            if base in FIELD_ALIASES:
                return base
    return ""

# Typographic Unicode variants (non-breaking hyphens/spaces, curly quotes)
# appear in LLM output and PDF text.  Every mapping is 1:1 in code points, so
# offsets stay valid against the original string.  Hyphens fold to spaces so
# "cash-equivalents" and "cash and cash equivalents" compare equal.
_UNICODE_FOLD = str.maketrans({
    "\u2010": " ", "\u2011": " ", "\u2012": " ", "\u2013": " ",
    "\u2014": " ", "\u2015": " ", "\u2212": " ",
    "-": " ",
    "\u00a0": " ", "\u2007": " ", "\u2009": " ", "\u202f": " ",
    "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
})


def _fold_unicode(text: str) -> str:
    return text.translate(_UNICODE_FOLD)


# One combined pattern for every alias, longest-first.  Matching all fields
# at once lets the *nearest* alias decide attribution instead of counting
# occurrences, so "cost of revenue" wins over the "revenue" inside it.
# Keys are folded the same way as the answer text.
_ALIAS_TO_FIELD: Dict[str, str] = {}
for _field, _aliases in FIELD_ALIASES.items():
    for _alias in _aliases:
        _ALIAS_TO_FIELD.setdefault(_fold_unicode(_alias).lower(), _field)

_ALL_ALIAS_PATTERN = re.compile(
    "|".join(re.escape(a) for a in sorted(_ALIAS_TO_FIELD, key=len, reverse=True)),
    re.IGNORECASE,
)


def _find_aliases(text: str, lo: int, hi: int) -> List[Tuple[str, int, int, str]]:
    """Alias matches within [lo, hi) as (field, start, end, alias_text)."""
    matches = []
    for match in _ALL_ALIAS_PATTERN.finditer(text, lo, hi):
        field = _ALIAS_TO_FIELD.get(match.group(0).lower())
        if field:
            matches.append((field, match.start(), match.end(), match.group(0)))
    return matches


def _nearest_alias(
    matches: List[Tuple[str, int, int, str]], offset: int
) -> Optional[Tuple[str, str]]:
    """(field, alias_text) of the alias closest to `offset`."""
    best: Optional[Tuple[str, str]] = None
    best_dist: Optional[int] = None
    for field, start, end, alias_text in matches:
        if end <= offset:
            dist = offset - end
        elif start >= offset:
            dist = start - offset
        else:
            dist = 0
        if best_dist is None or dist < best_dist:
            best_dist, best = dist, (field, alias_text)
    return best


# ─────────────────────────────────────────────────────────────────────────────
# PERIOD TOKENS
# Periods embedded in a model answer that contradict the expected period
# should disqualify the candidate number.
# ─────────────────────────────────────────────────────────────────────────────

_PERIOD_TOKEN = re.compile(
    r"\b(FY\s*\d{4}|Q[1-4]\s*FY\s*\d{4}|fiscal\s+\d{4}|(?:fiscal\s+year\s+)?\d{4})\b",
    re.IGNORECASE,
)


def _extract_year(period_str: str) -> Optional[int]:
    """Extract the 4-digit year from a period string like 'FY2024'."""
    m = re.search(r"\d{4}", period_str)
    return int(m.group(0)) if m else None


# ─────────────────────────────────────────────────────────────────────────────
# NUMBER EXTRACTION (same logic as original normalize_to_float, but also
# returns the character offset for context slicing)
# ─────────────────────────────────────────────────────────────────────────────

_NUMBER_PATTERN = re.compile(
    r"\$?\s*([\d,]+\.?\d*)\s*(?:(trillion|billion|million|thousand|[TBMK])\b)?",
    re.IGNORECASE,
)

_MULTIPLIER = {
    "trillion": 1e12, "t": 1e12,
    "billion": 1e9,   "b": 1e9,
    "million": 1e6,   "m": 1e6,
    "thousand": 1e3,  "k": 1e3,
}


def _extract_numbers_with_positions(text: str) -> List[Tuple[float, int]]:
    """
    Returns list of (value, char_offset) for every financial number found.
    Filters values ≤ 0.01 (noise).
    """
    results = []
    for match in _NUMBER_PATTERN.finditer(text):
        num_str = match.group(1).replace(",", "")
        unit = (match.group(2) or "").lower()
        try:
            val = float(num_str) * _MULTIPLIER.get(unit, 1.0)
            if val > 0.01:
                results.append((val, match.start()))
        except ValueError:
            continue
    return results


def _get_window_bounds(text: str, char_offset: int, n_lines: int = 2) -> Tuple[int, int]:
    """
    Character span covering the line holding char_offset and n_lines either
    side.  Offsets stay absolute so alias and period matches can be compared
    against the number's position.
    """
    lines = text.splitlines(keepends=True)
    target_idx, running = 0, 0
    for idx, line in enumerate(lines):
        running += len(line)
        if running > char_offset:
            target_idx = idx
            break

    lo = sum(len(line) for line in lines[: max(0, target_idx - n_lines)])
    hi = sum(len(line) for line in lines[: min(len(lines), target_idx + n_lines + 1)])
    return lo, hi


def _nearest_period_year(text: str, lo: int, hi: int, offset: int) -> Optional[int]:
    """Year of the period token closest to `offset` within [lo, hi)."""
    best_year: Optional[int] = None
    best_dist: Optional[int] = None
    for match in _PERIOD_TOKEN.finditer(text, lo, hi):
        year = _extract_year(match.group(0))
        if year is None:
            continue
        if match.end() <= offset:
            dist = offset - match.end()
        elif match.start() >= offset:
            dist = match.start() - offset
        else:
            dist = 0
        if best_dist is None or dist < best_dist:
            best_dist, best_year = dist, year
    return best_year


# ─────────────────────────────────────────────────────────────────────────────
# ATTRIBUTED CHECK
# ─────────────────────────────────────────────────────────────────────────────

def check_numerical_attributed(
    model_answer: str,
    ground_truth: float,
    canonical_field: str,
    expected_period: Optional[str] = None,
    tolerance: float = 0.02,
) -> Dict[str, Any]:
    """
    Attribution-aware numerical checker.

    Passes only when:
      1. A number within `tolerance` of `ground_truth` exists in the answer.
      2. The alias closest to that number (within ±2 lines) belongs to
         `canonical_field`.
      3. If `expected_period` is given, the closest period token does not
         contradict it, unless the same window also names the expected year.

    Returns a dict compatible with the original `check_numerical` return
    value, plus two extra keys:
      - attribution_checked (bool) — False means field not in FIELD_ALIASES
        and we fall back to the original unattributed behaviour.
      - attribution_match (str | None) — the alias text that matched.
    """
    if not model_answer:
        return {
            "passed": False,
            "best_match": None,
            "relative_error_pct": None,
            "tolerance_pct": tolerance * 100,
            "extracted_values": [],
            "attribution_checked": bool(_resolve_field(canonical_field)),
            "attribution_field": _resolve_field(canonical_field) or None,
            "attribution_match": None,
        }

    resolved_field = _resolve_field(canonical_field)
    attribution_checked = bool(resolved_field)

    expected_year = _extract_year(expected_period) if expected_period else None

    text = _fold_unicode(model_answer)
    candidates = _extract_numbers_with_positions(text)

    best_match: Optional[float] = None
    best_error = float("inf")
    best_alias: Optional[str] = None
    all_values = [v for v, _ in candidates]

    for val, offset in candidates:
        if ground_truth != 0:
            rel_err = abs(val - ground_truth) / abs(ground_truth)
        else:
            rel_err = abs(val)

        if rel_err > tolerance:
            continue  # Number is not close enough — skip attribution check.

        # ── Attribution check ────────────────────────────────────────────
        if attribution_checked:
            lo, hi = _get_window_bounds(text, offset)

            # The closest alias decides the line item, so "cost of revenue"
            # wins over the "revenue" embedded inside it.
            nearest = _nearest_alias(_find_aliases(text, lo, hi), offset)
            if nearest is None or nearest[0] != resolved_field:
                continue  # Number belongs to another line item, or to none.

            # Period: reject only when the window names no matching year and
            # the closest year token is a different one.
            if expected_year is not None:
                window_years = {
                    _extract_year(tok)
                    for tok in _PERIOD_TOKEN.findall(text[lo:hi])
                }
                if expected_year not in window_years:
                    nearest_year = _nearest_period_year(text, lo, hi, offset)
                    if nearest_year is not None and nearest_year != expected_year:
                        continue

            if rel_err < best_error:
                best_error = rel_err
                best_match = val
                best_alias = nearest[1]
        else:
            # Field not in vocabulary — fall back to original behaviour.
            if rel_err < best_error:
                best_error = rel_err
                best_match = val
                best_alias = None

    passed = best_match is not None and best_error <= tolerance

    return {
        "passed": passed,
        "best_match": best_match,
        "relative_error_pct": round(best_error * 100, 3) if best_match else None,
        "tolerance_pct": tolerance * 100,
        "extracted_values": all_values[:5],
        "attribution_checked": attribution_checked,
        "attribution_field": resolved_field or None,
        "attribution_match": best_alias,
    }


# ─────────────────────────────────────────────────────────────────────────────
# BACKWARD-COMPATIBLE WRAPPER (original signature)
# Drop this in place of check_numerical in run_eval.py.
# ─────────────────────────────────────────────────────────────────────────────

def check_numerical(
    model_answer: str,
    ground_truth: float,
    tolerance: float = 0.02,
    # Extra kwargs accepted but ignored so callers don't need to change.
    **kwargs,
) -> Dict[str, Any]:
    """
    Original-compatible wrapper.  Uses unattributed path (attribution_checked=False).
    Provided so that existing callers that don't pass canonical_field still work.
    """
    return check_numerical_attributed(
        model_answer=model_answer,
        ground_truth=ground_truth,
        canonical_field=kwargs.get("canonical_field", ""),
        expected_period=kwargs.get("expected_period"),
        tolerance=tolerance,
    )

